# Export all artifacts as ZIP
# ---------------------------------------------------------------------------

@router.post("/api/codegen/runs/{run_id}/export/zip")
async def export_zip(
    run_id: str = Path(...),
    user_id: str = Depends(current_user_id),
):
    blocked = _require_storage()
    if blocked:
        return blocked

    run = get_run_repository().get_any(run_id)
    if run is None:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NOT_FOUND",
                    "message": "Run not found.",
                },
            },
        )

    if not run.artifact_blob_root:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NO_ARTIFACTS",
                    "message": "No artifacts for this run.",
                },
            },
        )

    prefix = run.artifact_blob_root
    if not prefix.endswith("/"):
        prefix += "/"

    blob_names = list_blobs(prefix)

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in sorted(blob_names):
            rel = name[len(prefix):]
            if not rel:
                continue

            data = download_blob(name)
            if data:
                zf.writestr(rel, data)

    buf.seek(0)
    filename = f"codegen-{run_id[:8]}.zip"

    return StreamingResponse(
        buf,
        media_type="application/zip",
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
        },
    )


# ---------------------------------------------------------------------------
# Export the Solution Design Document (SDD) as .docx
# ---------------------------------------------------------------------------

_DOCX_MEDIA = (
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
)


def _extract_input_text(filename: str, data: bytes) -> str:
    """Best-effort text extraction from a run's input file for the SDD process description.

    Handles text/markdown/json and .docx (python-docx); other binaries are skipped.
    """
    name = (filename or "").lower()

    if name.endswith((".md", ".markdown", ".txt", ".json", ".csv")):
        try:
            return data.decode("utf-8")
        except UnicodeDecodeError:
            return ""

    if name.endswith(".docx"):
        try:
            from docx import Document

            doc = Document(io.BytesIO(data))
            lines = [p.text for p in doc.paragraphs if p.text.strip()]

            for table in doc.tables:
                for row in table.rows:
                    cells = [c.text.strip() for c in row.cells]
                    if any(cells):
                        lines.append(" | ".join(cells))

            return "\n".join(lines)
        except Exception:
            return ""

    return ""


@router.post("/api/codegen/runs/{run_id}/export/sdd")
async def export_sdd(
    run_id: str = Path(...),
    user_id: str = Depends(current_user_id),
):
    """Generate a Solution Design Document (.docx) for a run from its input
    files / approved SDD (the authoritative design spec that drove code generation).
    Runs the S-agent SDD pipeline one-shot (auto-selects the recommended solution option).
    """
    blocked = _require_storage()
    if blocked:
        return blocked

    run = get_run_repository().get_any(run_id)
    if run is None:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NOT_FOUND",
                    "message": "Run not found.",
                },
            },
        )

    # Build the process description from the workflow's input files.
    files = get_file_repository().list(run.workflow_id)
    parts = []

    for f in files:
        if not f.blob_path:
            continue

        data = download_blob(f.blob_path)
        if not data:
            continue

        text = _extract_input_text(f.filename, data)
        if text.strip():
            parts.append(f"=== Source: {f.filename} ===\n{text}")

    process_description = "\n\n".join(parts).strip()

    if not process_description:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NO_SPEC",
                    "message": (
                        "No readable specification/SDD input files for this "
                        "run to build a final SDD export from."
                    ),
                },
            },
        )

    try:
        docx = await run_in_threadpool(
            generate_sdd_docx,
            process_description,
        )
    except RuntimeError as exc:
        logger.warning("[sdd] generation unavailable: %s", exc)
        return JSONResponse(
            status_code=503,
            content={
                "ok": False,
                "error": {
                    "code": "AI_UNAVAILABLE",
                    "message": str(exc),
                },
            },
        )
    except Exception:
        logger.exception("[sdd] generation failed run=%s", run_id)
        return JSONResponse(
            status_code=500,
            content={
                "ok": False,
                "error": {
                    "code": "SDD_FAILED",
                    "message": "SDD generation failed.",
                },
            },
        )

    filename = f"SDD-{run_id[:8]}.docx"

    return StreamingResponse(
        io.BytesIO(docx),
        media_type=_DOCX_MEDIA,
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
        },
    )
