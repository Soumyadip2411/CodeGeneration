"""Artifact endpoints - tree listing, file content, ZIP export."""

from __future__ import annotations

import io
import logging
import zipfile

from fastapi import APIRouter, Depends, Path, Query
from fastapi.responses import JSONResponse, StreamingResponse
from starlette.concurrency import run_in_threadpool

from shared_lib.auth import current_user_id
from shared_lib.storage import is_cosmos_enabled

from services.files import get_file_repository
from services.runs import get_run_repository
from services.sdd import generate_sdd_docx
from services.storage import download_blob, list_blobs


logger = logging.getLogger(__name__)
router = APIRouter()


def _require_storage():
    if not is_cosmos_enabled():
        return JSONResponse(
            status_code=503,
            content={
                "ok": False,
                "error": {
                    "code": "COSMOS_DISABLED",
                    "message": "Cosmos DB not configured.",
                },
            },
        )
    return None


# ---------------------------------------------------------------------------
# Artifact tree (list files generated by a run)
# ---------------------------------------------------------------------------

@router.get("/api/codegen/runs/{run_id}/artifacts/tree")
async def get_artifact_tree(
    run_id: str = Path(...),
    user_id: str = Depends(current_user_id),
):
    blocked = _require_storage()
    if blocked:
        return blocked

    run = get_run_repository().get_any(run_id)
    if run is None:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NOT_FOUND",
                    "message": "Run not found.",
                },
            },
        )

    if not run.artifact_blob_root:
        return {
            "ok": True,
            "tree": [],
            "file_count": 0,
        }

    prefix = run.artifact_blob_root
    if not prefix.endswith("/"):
        prefix += "/"

    blob_names = list_blobs(prefix)

    # Convert to relative paths
    tree = []
    for name in sorted(blob_names):
        rel = name[len(prefix):]
        if rel:
            size = 0  # Size would require individual blob properties call; skip for listing
            tree.append({
                "path": rel,
                "name": rel.split("/")[-1],
            })

    return {
        "ok": True,
        "tree": tree,
        "file_count": len(tree),
        "blob_root": run.artifact_blob_root,
    }


# ---------------------------------------------------------------------------
# Read a single artifact file
# ---------------------------------------------------------------------------

@router.get("/api/codegen/runs/{run_id}/artifacts/file")
async def get_artifact_file(
    run_id: str = Path(...),
    path: str = Query(..., description="Relative file path within the artifact root"),
    user_id: str = Depends(current_user_id),
):
    blocked = _require_storage()
    if blocked:
        return blocked

    run = get_run_repository().get_any(run_id)
    if run is None:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NOT_FOUND",
                    "message": "Run not found.",
                },
            },
        )

    if not run.artifact_blob_root:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "NO_ARTIFACTS",
                    "message": "No artifacts for this run.",
                },
            },
        )

    blob_path = f"{run.artifact_blob_root}/{path}"
    data = download_blob(blob_path)

    if data is None:
        return JSONResponse(
            status_code=404,
            content={
                "ok": False,
                "error": {
                    "code": "FILE_NOT_FOUND",
                    "message": f"File '{path}' not found.",
                },
            },
        )

    # Try to decode as text
    try:
        content = data.decode("utf-8")
        return {
            "ok": True,
            "path": path,
            "content": content,
        }
    except UnicodeDecodeError:
        return StreamingResponse(
            io.BytesIO(data),
            media_type="application/octet-stream",
            headers={
                "Content-Disposition": f'attachment; filename="{path.split("/")[-1]}"'
            },
        )


